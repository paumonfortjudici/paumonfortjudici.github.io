// Copies the shared kit INTO a slide, because Chrome blocks <use>/filter references to other files when an SVG is opened from file://.
//   node kit/inline-kit.mjs --new slide-1.svg     create slide-1.svg from kit/slide-template.svg (refuses to overwrite) and inline the kit
//   node kit/inline-kit.mjs slide-1.svg [...]     refresh the kit block in existing slides (everything outside the markers is left alone)
//   add  --keep-all  to inline EVERYTHING (default: PRUNE - only the symbols / filters / masks / lockups your slide actually references)
// The kit block sits between  <!--KIT:BEGIN-->  and  <!--KIT:END-->  : tokens.css + fonts.css as one <style>, plus the <defs> of
// texture.svg, sunburst.svg, motifs.svg, titles.svg and ona-parts.svg. Never edit inside the markers; re-run the script instead.
// Re-run it after EVERY change that adds a new kit reference (a new <use href="#..."> or filter="url(#...)"), or the new piece will be missing.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const read = (f) => fs.readFileSync(path.join(HERE, f), 'utf8')
const KIT_FILES = ['texture.svg', 'sunburst.svg', 'motifs.svg', 'titles.svg', 'ona-parts.svg']
const ITEM = /<(symbol|filter|mask|linearGradient|radialGradient|g)\s+[^>]*?id="([^"]+)"[^>]*>[\s\S]*?<\/\1>/g

function allItems() {
  const items = new Map()
  for (const f of KIT_FILES) {
    const svg = read(f)
    // blank out comments first (same length) so a mention of the tag inside a comment is never matched
    const masked = svg.replace(/<!--[\s\S]*?-->/g, (c) => ' '.repeat(c.length))
    const open = masked.match(/<defs id="kit-[^"]+">/)
    if (!open) throw new Error(`no kit defs element in kit/${f}`)
    const end = masked.indexOf('</defs>', open.index)
    const inner = masked.slice(open.index + open[0].length, end)
    const orig = svg.slice(open.index + open[0].length, end)
    ITEM.lastIndex = 0
    let m
    while ((m = ITEM.exec(inner))) items.set(m[2], orig.slice(m.index, m.index + m[0].length))
  }
  return items
}
const refsIn = (text) => [...text.matchAll(/(?:href="#|url\(#)([^")]+)/g)].map((m) => m[1])

function kitBlock(slideSvg, keepAll) {
  const css = [read('fonts.css'), read('tokens.css')].join('\n').replace(/@import[^;]*;/g, '')
  const items = allItems()
  let keep
  if (keepAll) keep = new Set(items.keys())
  else {
    // everything referenced outside the kit block, plus transitive references between kit items
    const outside = slideSvg.replace(/<!--KIT:BEGIN[\s\S]*?<!--KIT:END-->/, '')
    const q = refsIn(outside).filter((id) => items.has(id))
    keep = new Set()
    while (q.length) {
      const id = q.pop()
      if (keep.has(id)) continue
      keep.add(id)
      for (const r of refsIn(items.get(id))) if (items.has(r) && !keep.has(r)) q.push(r)
    }
  }
  const body = [...items.entries()].filter(([id]) => keep.has(id)).map(([, t]) => '  ' + t).join('\n')
  return `<!--KIT:BEGIN generated by kit/inline-kit.mjs (${keepAll ? 'all' : keep.size + ' items used'}) - do not edit between the markers, re-run the script-->\n<style><![CDATA[\n${css}\n]]></style>\n<defs id="kit-inlined">\n${body}\n</defs>\n<!--KIT:END-->`
}

const argv = process.argv.slice(2)
if (!argv.length) { console.error('usage: node kit/inline-kit.mjs [--keep-all] --new slide-1.svg | slide-1.svg [...]'); process.exit(2) }
const keepAll = argv.includes('--keep-all')
const rest = argv.filter((a) => a !== '--keep-all')
const isNew = rest[0] === '--new'
const files = isNew ? rest.slice(1) : rest
for (const file of files) {
  const p = path.resolve(file)
  let svg
  if (isNew) {
    if (fs.existsSync(p)) { console.error('refusing to overwrite', p); process.exit(1) }
    svg = read('slide-template.svg')
  } else {
    svg = fs.readFileSync(p, 'utf8')
  }
  if (!/<!--KIT:BEGIN[\s\S]*?<!--KIT:END-->/.test(svg)) { console.error(`${file}: no <!--KIT:BEGIN--> ... <!--KIT:END--> markers`); process.exit(1) }
  const out = svg.replace(/<!--KIT:BEGIN[\s\S]*?<!--KIT:END-->/, () => kitBlock(svg, keepAll))
  fs.writeFileSync(p, out)
  console.log(`${isNew ? 'created' : 'refreshed'} ${file}  (${(out.length / 1024).toFixed(1)} KB)`)
}
